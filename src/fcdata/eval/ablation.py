"""Ablation over the *kind* of synthetic data used for SFT.

WHY this experiment exists
--------------------------
"Function-calling fine-tuning data synthesis" is only worth doing if the
synthesised data adds capability that the raw dataset does not already contain.
The honest way to show that is an ablation ladder where every rung trains the
same architecture for the same budget and differs **only** in the data mix:

===============  =========================================  ====================
config           SFT records used                           synthesis cost
===============  =========================================  ====================
``raw_only``     raw Spider examples only                   0 tokens (baseline)
``plus_cot``     raw + CoT rationales                       CoT tokens
``plus_hard_neg``raw + CoT + paraphrase + hard negatives    all synthesis tokens
===============  =========================================  ====================

Two numbers are recorded per rung and they are the point of the figure
``cost_vs_quality.png``: the **synthesis tokens invested** (cost) and the
**execution accuracy** measured by really running the generated SQL (quality).
Every rung is trained and evaluated through the public train/eval APIs, so the
comparison is apples-to-apples.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Sequence

from ..records import Example, SFTRecord, write_json
from .pipeline import (
    SFTBundle,
    cost_for_kinds,
    load_sft_bundle,
    quick_cfg,
    resample_by_difficulty,
    select_kinds,
    synth_cost_by_kind,
    synth_tokens_of,
    train_and_evaluate,
    write_rows_json_csv,
)

#: The ladder, in the order it must be reported. ``kinds`` is exhaustive and
#: ``resample`` says whether difficulty-weighted duplication is applied.
ABLATION_CONFIGS: dict[str, dict[str, Any]] = {
    "raw_only": {
        "kinds": ("raw",),
        "resample": False,
        "description": "Raw Spider examples only (no synthesis) -- the baseline.",
    },
    "plus_cot": {
        "kinds": ("raw", "cot"),
        "resample": False,
        "description": "Raw + chain-of-thought rationales generated by the cheap model.",
    },
    "plus_hard_negatives": {
        "kinds": ("raw", "cot", "paraphrase", "hard_negative"),
        "resample": True,
        "description": (
            "Full synthesis mix: raw + CoT + paraphrases + error->correction hard "
            "negatives, with difficulty-weighted resampling of the hard records."
        ),
    },
}

#: CSV column order (also the table order in the report).
ABLATION_COLUMNS: tuple[str, ...] = (
    "config", "n_sft_records", "n_unique_records", "synth_tokens", "synth_cost_usd",
    "cost_from_ledger", "exec_acc", "exec_acc_ci_lo", "exec_acc_ci_hi", "exact_match",
    "executable_rate", "token_acc", "skeleton_match", "table_set_match",
    "column_f1", "clause_match_mean", "n_eval", "delta_exec_acc", "train_seconds",
    "kind_counts",
)


@dataclass
class AblationRow:
    """One rung of the ladder: data mix in, measured capability out."""

    config: str
    description: str
    kinds: tuple[str, ...]
    n_sft_records: int = 0
    n_unique_records: int = 0
    synth_tokens: int = 0
    synth_cost_usd: float = 0.0
    cost_from_ledger: bool = False
    exec_acc: float = 0.0
    exec_acc_ci: tuple[float, float] = (0.0, 0.0)
    exact_match: float = 0.0
    executable_rate: float = 0.0
    n_eval: int = 0
    delta_exec_acc: float | None = None
    train_seconds: float = 0.0
    kind_counts: dict[str, int] = field(default_factory=dict)
    train_dir: str = ""
    eval_dir: str = ""
    # ---- partial credit: the signal that survives 0% strict accuracy -------
    token_acc: float = 0.0
    skeleton_match: float = 0.0
    table_set_match: float = 0.0
    column_f1: float = 0.0
    clause_match_mean: float = 0.0
    partial_failures: dict[str, int] = field(default_factory=dict)
    partial_ci: dict[str, list[float]] = field(default_factory=dict)
    delta_table_set_match: float | None = None

    def as_row(self) -> dict[str, Any]:
        """Flat dict for CSV/JSON/markdown (bootstrap CI unpacked).

        Partial-credit metrics appear **both** flat (convenient for CSV columns)
        and nested under ``partial`` (the shape the report and
        ``scripts/show_results.py`` read). Duplication is deliberate: flattening
        alone makes the JSON awkward to consume generically, and nesting alone
        breaks the one-row-per-config CSV.
        """
        lo, hi = self.exec_acc_ci
        partial = {
            "token_acc": self.token_acc,
            "skeleton_match": self.skeleton_match,
            "table_set_match": self.table_set_match,
            "column_f1": self.column_f1,
            "clause_match_mean": self.clause_match_mean,
            "failure_taxonomy": dict(self.partial_failures),
            "ci": {k: list(v) for k, v in self.partial_ci.items()},
        }
        return {
            "config": self.config,
            "description": self.description,
            "kinds": ",".join(self.kinds),
            "n_sft_records": self.n_sft_records,
            "n_unique_records": self.n_unique_records,
            "synth_tokens": self.synth_tokens,
            "synth_cost_usd": round(self.synth_cost_usd, 6),
            "cost_from_ledger": self.cost_from_ledger,
            "exec_acc": self.exec_acc,
            "exec_acc_ci_lo": lo,
            "exec_acc_ci_hi": hi,
            "exact_match": self.exact_match,
            "executable_rate": self.executable_rate,
            "token_acc": self.token_acc,
            "skeleton_match": self.skeleton_match,
            "table_set_match": self.table_set_match,
            "column_f1": self.column_f1,
            "clause_match_mean": self.clause_match_mean,
            "partial": partial,
            "partial_failures": dict(self.partial_failures),
            "n_eval": self.n_eval,
            "delta_exec_acc": self.delta_exec_acc,
            "delta_table_set_match": self.delta_table_set_match,
            "train_seconds": self.train_seconds,
            "kind_counts": dict(self.kind_counts),
            "train_dir": self.train_dir,
            "eval_dir": self.eval_dir,
        }


def build_ablation_mix(bundle: SFTBundle,
                       config_name: str,
                       *,
                       seed: int = 17) -> list[SFTRecord]:
    """Records one ablation config trains on (filtered + optionally resampled)."""
    if config_name not in ABLATION_CONFIGS:
        raise KeyError(
            f"unknown ablation config {config_name!r}; "
            f"have {sorted(ABLATION_CONFIGS)}")
    spec = ABLATION_CONFIGS[config_name]
    picked = select_kinds(bundle.train, spec["kinds"])
    if spec.get("resample"):
        picked = resample_by_difficulty(picked, seed=seed)
    return picked


def run_ablation(cfg: Any,
                 spider_data: Any,
                 ablation_cfg: Any,
                 out_dir: str | Path,
                 *,
                 quick: bool = False,
                 bundle: SFTBundle | None = None,
                 train_fn: Callable[..., dict[str, Any]] | None = None,
                 load_fn: Callable[..., tuple[Any, Any]] | None = None,
                 generate_fn: Callable[..., str] | None = None,
                 prompt_fn: Callable[..., str] | None = None,
                 progress: bool = True) -> dict[str, Any]:
    """Run every configured ablation rung: train, evaluate, account tokens.

    Parameters
    ----------
    cfg:
        Pipeline config. With ``quick=True`` training/eval are shrunk so the
        whole ladder finishes in well under a minute on CPU.
    spider_data:
        ``SpiderData`` for schemas + sqlite paths.
    ablation_cfg:
        ``cfg.ablation``-shaped object; ``.configs`` names the rungs and
        ``.dev_sample`` caps eval examples per rung (0 = use ``cfg.ev``).
    out_dir:
        Where per-rung train/eval dirs and ``ablation.json``/``ablation.csv`` go.
    quick:
        Smoke mode (1 epoch, few eval examples). Never used for reported numbers.
    train_fn / load_fn / generate_fn:
        Injection points for tests (default: the real trainer/evaluator).

    Returns
    -------
    dict
        ``{"rows": [...], "baseline": "raw_only", "best": {...}, "n_configs": n,
        "source": <where the SFT corpus came from>, "quick": bool}``.
    """
    run_cfg = quick_cfg(cfg) if quick else cfg
    work = Path(out_dir)
    work.mkdir(parents=True, exist_ok=True)

    sft = bundle or load_sft_bundle(run_cfg, spider_data)
    if not sft.train:
        raise RuntimeError(
            "no SFT records available for ablation: run the format stage first "
            f"(looked in {cfg.paths.sft_dir})")
    cost_by_kind = synth_cost_by_kind(run_cfg)

    names: Sequence[str] = list(getattr(ablation_cfg, "configs", None)
                                or list(ABLATION_CONFIGS))
    unknown = [n for n in names if n not in ABLATION_CONFIGS]
    if unknown:
        raise KeyError(f"unknown ablation configs {unknown}; have {sorted(ABLATION_CONFIGS)}")

    eval_examples = _ablation_eval_examples(run_cfg, sft, ablation_cfg)
    warnings = _degeneracy_warnings(sft, names)
    if warnings and progress:
        for w in warnings:
            print(f"[ablation] WARNING: {w}", flush=True)

    rows: list[AblationRow] = []
    for i, name in enumerate(names, start=1):
        spec = ABLATION_CONFIGS[name]
        if progress:
            print(f"[ablation] ({i}/{len(names)}) {name}: training...", flush=True)
        records = build_ablation_mix(sft, name, seed=int(getattr(run_cfg, "seed", 17)))
        row = AblationRow(
            config=name,
            description=str(spec["description"]),
            kinds=tuple(spec["kinds"]),
            n_sft_records=len(records),
            n_unique_records=len({r.id for r in records}),
            synth_tokens=synth_tokens_of(records),
            kind_counts=_kind_counts(records),
        )
        cost, from_ledger = cost_for_kinds(run_cfg, spec["kinds"], records, cost_by_kind)
        row.synth_cost_usd = cost
        row.cost_from_ledger = from_ledger

        result = train_and_evaluate(
            run_cfg, spider_data, records, sft.dev, eval_examples,
            work / name, train_fn=train_fn, load_fn=load_fn,
            generate_fn=generate_fn, prompt_fn=prompt_fn, progress=progress)
        ev = result["eval"]
        row.exec_acc = float(ev.get("exec_acc", 0.0))
        ci = ev.get("exec_acc_ci", [0.0, 0.0])
        row.exec_acc_ci = (float(ci[0]), float(ci[1]))
        row.exact_match = float(ev.get("exact_match", 0.0))
        row.executable_rate = float(ev.get("executable_rate", 0.0))
        row.n_eval = int(ev.get("n", 0))
        row.train_seconds = float(result.get("train_seconds", 0.0))
        row.train_dir = result["train_dir"]
        row.eval_dir = result["eval_dir"]
        partial = ev.get("partial") or {}
        row.token_acc = float(partial.get("token_acc", 0.0))
        row.skeleton_match = float(partial.get("skeleton_match", 0.0))
        row.table_set_match = float(partial.get("table_set_match", 0.0))
        row.column_f1 = float(partial.get("column_f1", 0.0))
        row.clause_match_mean = float(partial.get("clause_match_mean", 0.0))
        row.partial_failures = {
            k: int(v.get("n", 0))
            for k, v in (partial.get("failure_taxonomy") or {}).items()
            if int(v.get("n", 0) or 0) > 0
        }
        row.partial_ci = {
            k: [float(v[0]), float(v[1])]
            for k, v in (partial.get("ci") or {}).items()
            if isinstance(v, (list, tuple)) and len(v) == 2
        }
        rows.append(row)
        if progress:
            print(f"[ablation] {name}: exec_acc={row.exec_acc * 100:.1f}% "
                  f"token_acc={row.token_acc * 100:.1f}% "
                  f"tables={row.table_set_match * 100:.1f}% "
                  f"synth_tokens={row.synth_tokens:,}", flush=True)

    # deltas are measured against raw_only when present, else the first rung
    baseline = next((r for r in rows if r.config == "raw_only"), rows[0] if rows else None)
    for row in rows:
        if baseline is not None:
            row.delta_exec_acc = round(row.exec_acc - baseline.exec_acc, 6)
            row.delta_table_set_match = round(
                row.table_set_match - baseline.table_set_match, 6)

    flat = [r.as_row() for r in rows]
    payload = {
        "rows": flat,
        "baseline": baseline.config if baseline is not None else "",
        "best": _best(rows),
        "n_configs": len(rows),
        "source": sft.source,
        "quick": bool(quick),
        "eval_split": str(getattr(getattr(run_cfg, "ev", None), "split", "dev")),
        "n_eval_examples": len(eval_examples),
        "synth_cost_by_kind": cost_by_kind,
        "sft_kind_counts": sft.kind_counts(),
        "n_sft_available": len(sft.train),
        "warnings": warnings,
        "degenerate": bool(warnings),
    }
    write_rows_json_csv(flat, work / "ablation.json", work / "ablation.csv",
                        ABLATION_COLUMNS, payload)
    if progress:
        print(f"[ablation] wrote {work / 'ablation.json'} and ablation.csv", flush=True)
    return payload


def _best(rows: Sequence[AblationRow]) -> dict[str, Any]:
    if not rows:
        return {}
    best = max(rows, key=lambda r: (r.exec_acc, -r.synth_tokens))
    return {"config": best.config, "exec_acc": best.exec_acc,
            "synth_tokens": best.synth_tokens,
            "synth_cost_usd": best.synth_cost_usd}


def _kind_counts(records: Sequence[SFTRecord]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for r in records:
        counts[r.kind] = counts.get(r.kind, 0) + 1
    return dict(sorted(counts.items()))


def _degeneracy_warnings(sft: SFTBundle, names: Sequence[str]) -> list[str]:
    """Flag ablations that cannot actually distinguish their configs.

    An ablation whose rungs all train on the same records measures nothing, and
    reporting it as a result would be misleading. The two realistic causes are a
    corpus with no synthetic records (synth stage not run yet) and an empty
    synthesis after validation dropped everything. Both are reported as explicit
    warnings, stored in ``ablation.json``, and surfaced in the markdown report.
    """
    warnings: list[str] = []
    available = sft.kind_counts()
    synthetic = {k: v for k, v in available.items() if k != "raw" and v > 0}
    if not synthetic:
        warnings.append(
            "the SFT corpus contains no synthetic records, so every ablation "
            "config trains on the same raw data: run the synth + validate + "
            "format stages to make this experiment meaningful")
    else:
        for name in names:
            kinds = [k for k in ABLATION_CONFIGS[name]["kinds"] if k != "raw"]
            if kinds and not any(available.get(k, 0) > 0 for k in kinds):
                warnings.append(
                    f"config {name!r} needs kinds {kinds} but the corpus has none "
                    f"of them (available: {sorted(synthetic)})")
    return warnings


def _ablation_eval_examples(cfg: Any, bundle: SFTBundle,
                            ablation_cfg: Any) -> list[Example]:
    """Eval examples for one rung, honouring ``ablation.dev_sample``."""
    examples = list(bundle.eval_examples)
    if not examples:
        raise RuntimeError("no dev examples available to evaluate the ablation")
    sample = int(getattr(ablation_cfg, "dev_sample", 0) or 0)
    if sample > 0:
        return examples[:sample]
    return examples


def load_ablation(path: str | Path) -> dict[str, Any]:
    """Read a previously written ``ablation.json`` (used by the report stage)."""
    from ..records import read_json  # noqa: PLC0415 - local import

    data = read_json(path, None)
    if data is None:
        raise FileNotFoundError(f"no ablation results at {path}")
    return data
